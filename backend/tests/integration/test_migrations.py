from alembic import command
from conftest import alembic_config
from sqlalchemy import inspect

from app.db import make_engine

CATALOGUE_TABLES = {"bay_types", "bays", "services", "opening_hours", "opening_hours_breaks"}


def test_upgrade_head_on_empty_database_creates_settings(fresh_database_url: str) -> None:
    command.upgrade(alembic_config(fresh_database_url), "head")
    columns = {c["name"] for c in inspect(make_engine(fresh_database_url)).get_columns("settings")}
    assert columns == {"key", "value", "updated_at"}


def test_downgrade_to_base_and_upgrade_again(fresh_database_url: str) -> None:
    cfg = alembic_config(fresh_database_url)
    command.upgrade(cfg, "head")
    command.downgrade(cfg, "base")
    assert "settings" not in inspect(make_engine(fresh_database_url)).get_table_names()
    command.upgrade(cfg, "head")
    assert "settings" in inspect(make_engine(fresh_database_url)).get_table_names()


def test_models_match_migrations(fresh_database_url: str) -> None:
    cfg = alembic_config(fresh_database_url)
    command.upgrade(cfg, "head")
    command.check(cfg)  # raises AutogenerateDiffsDetected on drift


def test_upgrade_head_creates_catalogue_tables(fresh_database_url: str) -> None:
    command.upgrade(alembic_config(fresh_database_url), "head")
    assert set(inspect(make_engine(fresh_database_url)).get_table_names()) >= CATALOGUE_TABLES


def test_downgrade_to_0001_drops_catalogue_tables(fresh_database_url: str) -> None:
    cfg = alembic_config(fresh_database_url)
    command.upgrade(cfg, "head")
    command.downgrade(cfg, "0001")
    tables = set(inspect(make_engine(fresh_database_url)).get_table_names())
    assert tables.isdisjoint(CATALOGUE_TABLES)
    assert "settings" in tables


def test_upgrade_head_creates_reservations(fresh_database_url: str) -> None:
    command.upgrade(alembic_config(fresh_database_url), "head")
    assert "reservations" in inspect(make_engine(fresh_database_url)).get_table_names()


def test_downgrade_to_0002_drops_reservations(fresh_database_url: str) -> None:
    cfg = alembic_config(fresh_database_url)
    command.upgrade(cfg, "head")
    command.downgrade(cfg, "0002")
    tables = set(inspect(make_engine(fresh_database_url)).get_table_names())
    assert "reservations" not in tables
    assert "services" in tables
